export const TARGETS = [
  { id: 0, name: 'Correct implementation', detail: 'Lifetime spending remains independent of retained history.' },
  { id: 1, name: 'Memory eviction refund', detail: 'Rebuilds remaining allowance from an incomplete memory window.' },
  { id: 2, name: 'Rejected request debit', detail: 'Consumes allowance even when the request is rejected.' },
  { id: 3, name: 'Stale permission replay', detail: 'Reuses an earlier approval after the owner revokes the session.' },
];
export const ACTIONS = ['Spend', 'Wrong recipient', 'Preview', 'Revoke', 'Advance time', 'Recall', 'Wrong caller', 'Remember note'];
export const FAILURES = ['No failure found', 'Budget conservation violated', 'Rejected request changed allowance', 'Authorization after revocation', 'Decision differs from independent oracle', 'Preview changed allowance'];
export const DECISIONS = ['Allowed', 'Revoked', 'Wrong delegate', 'Expired', 'Wrong recipient', 'Zero amount', 'Transfer limit', 'Budget limit'];
const unsigned = value => BigInt.asUintN(64, value);

export async function loadEngine(bytes) {
  const { instance } = await WebAssembly.instantiate(bytes, {
    env: { __fe_revert: () => { throw new Error('Fe engine reverted; this run produced no valid result.'); } },
  });
  return instance.exports;
}

function decodeState(raw) {
  const value = unsigned(raw);
  return {
    remaining: Number(value & 65535n), spent: Number((value >> 16n) & 65535n),
    retained: Number((value >> 32n) & 255n), revoked: Boolean((value >> 40n) & 255n),
    failure: Number((value >> 48n) & 255n), decision: Number((value >> 56n) & 255n),
  };
}

// This module contains presentation/ABI code only. All state and verdicts below
// come from the Fe-compiled WASM exports, including the corrected-target replay.
export function campaign(engine, { target = 1, seed = '0', cases = 64, steps = 64 } = {}) {
  target = Number(target); cases = Number(cases); steps = Number(steps);
  if (!Number.isInteger(target) || target < 0 || target > 3) throw new Error('Target must be 0–3.');
  if (!Number.isInteger(cases) || cases < 1 || cases > 4096) throw new Error('Cases must be 1–4096.');
  if (!Number.isInteger(steps) || steps < 1 || steps > 64) throw new Error('Steps must be 1–64.');
  const start = BigInt(seed);
  if (start < 0n || start > 0xffffffffffffffffn) throw new Error('Seed must fit an unsigned 64-bit integer.');
  const args = [BigInt(target), start, BigInt(cases), BigInt(steps)];
  const attempts = Number(engine.fg_search(...args));
  const base = { schemaVersion: 1, compiler: 'Fe 26.7.0', target, targetName: TARGETS[target].name, startSeed: String(start), cases, steps };
  if (attempts === 0) return { ...base, found: false, casesChecked: cases, actionsBound: cases * steps };
  const failingSeed = BigInt.asUintN(64, start + BigInt(attempts - 1));
  const info = unsigned(engine.fg_info(BigInt(target), failingSeed, BigInt(steps)));
  const failure = Number(info & 255n);
  const generatedLength = Number((info >> 8n) & 255n);
  const reducedLength = Number((info >> 16n) & 255n);
  const replays = Number(info >> 32n);
  const originalFailure = unsigned(engine.fg_failure(BigInt(target), failingSeed, BigInt(steps)));
  const originalLength = Number(originalFailure >> 8n) + 1;
  const validation = Number(engine.fg_validate(BigInt(target), failingSeed, BigInt(steps)));
  const trace = (reduced, length) => Array.from({ length }, (_, index) => {
    const raw = unsigned(engine.fg_action(BigInt(target), failingSeed, BigInt(steps), BigInt(reduced), BigInt(index)));
    const opcode = Number(raw >> 32n), value = Number(raw & 0xffffffffn);
    const state = decodeState(engine.fg_state(BigInt(target), failingSeed, BigInt(steps), BigInt(reduced), BigInt(index + 1), BigInt(target)));
    const correctedState = decodeState(engine.fg_state(BigInt(target), failingSeed, BigInt(steps), BigInt(reduced), BigInt(index + 1), 0n));
    return { index, opcode, action: ACTIONS[opcode], value, state, correctedState };
  });
  return {
    ...base, found: true, casesChecked: attempts, failingSeed: String(failingSeed),
    failureCode: failure, failure: FAILURES[failure], generatedLength, originalLength, reducedLength, reductionReplays: replays,
    deletionMinimal: Boolean(validation & 1), correctedReplayPasses: Boolean(validation & 2),
    originalTrace: trace(0, originalLength), reducedTrace: trace(1, reducedLength),
    limitation: 'Intentional model mutants. A finite campaign is not a security proof. Reduction preserves the same failure class and is single-action-deletion minimal, not globally shortest.',
  };
}

export function feReproducer(report) {
  if (!report.found) throw new Error('No failing trace to export.');
  const assignments = report.reducedTrace.map((a, i) => `    trace.actions[${i}] = Action { opcode: ${a.opcode}, value: ${a.value} }`).join('\n');
  return `// Generated by FeGuard; intentional mutant ${report.target}, seed ${report.failingSeed}.\n` +
    `// Copy this file into src/ and run: fe test --filter exported_counterexample\n` +
    `use ingot::fuzz::{Action, empty_trace, replay, one_minimal}\nuse ingot::guard_machine::guard\n\n` +
    `#[test]\nfn exported_counterexample() {\n    var trace = empty_trace()\n    trace.len = ${report.reducedLength}\n${assignments}\n` +
    `    var mutant = guard(${report.target})\n    assert!(replay(mut mutant, trace).code == ${report.failureCode})\n` +
    `    assert!(one_minimal(mut mutant, trace, code: ${report.failureCode}))\n    var fixed = guard(0)\n    assert!(replay(mut fixed, trace).code == 0)\n}\n`;
}
